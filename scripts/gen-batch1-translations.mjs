// ---------------------------------------------------------------------------
// Apply translations
// ---------------------------------------------------------------------------

let addedUnits = 0;
let addedAbilities = 0;
let addedWeapons = 0;

// Units
for (const [unitId, nameFr] of Object.entries(UNIT_TRANSLATIONS)) {
  if (!trans.units[unitId]) {
    trans.units[unitId] = nameFr;
    addedUnits++;
  }
}

// Abilities — scan all batch-1 abilities and apply name map
for (const ability of udb.abilities) {
  if (!b1UnitIds.has(ability.unit_id) || !ability.name) continue;
  const key = `${ability.unit_id}:${ability.name}`;
  if (trans.abilities[key]) continue;
  const nameFr = ABILITY_NAME_MAP[ability.name];
  if (nameFr) {
    trans.abilities[key] = { name_fr: nameFr, description_fr: null };
    addedAbilities++;
  }
}

// Weapons — scan all batch-1 weapons and apply name map
for (const weapon of udb.weapons) {
  if (!b1UnitIds.has(weapon.unit_id) || !weapon.name) continue;
  const key = `${weapon.unit_id}:${weapon.name}`;
  if (trans.weapons[key]) continue;
  const nameFr = WEAPON_NAME_MAP[weapon.name];
  if (nameFr) {
    trans.weapons[key] = nameFr;
    addedWeapons++;
  }
}

// Validate + write
const json = JSON.stringify(trans, null, 2);
JSON.parse(json); // throws if invalid
writeFileSync(join(REPO_ROOT, "scripts/data/translations_fr.json"), json + "\n", "utf-8");

console.log(`Added ${addedUnits} unit names, ${addedAbilities} abilities, ${addedWeapons} weapons`);
console.log(`Totals — units: ${Object.keys(trans.units).length}, abilities: ${Object.keys(trans.abilities).length}, weapons: ${Object.keys(trans.weapons).length}`);
